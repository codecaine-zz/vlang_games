pub fn draw_char(renderer &Renderer, x int, y int, ch u8, scale int, col Color) {
	if ch < 32 || ch > 93 {
		return
	}
	idx := (int(ch) - 32) * 8
	set_render_draw_color(renderer, col.r, col.g, col.b, col.a)

	for row in 0 .. 8 {
		bits := font_8x8[idx + row]
		for col_i in 0 .. 8 {
			if (bits & (1 << (7 - col_i))) != 0 {
				rect := Rect{
					x: x + col_i * scale
					y: y + row * scale
					w: scale
					h: scale
				}
				render_fill_rect(renderer, &rect)
			}
		}
	}
}

pub fn draw_text(renderer &Renderer, x int, y int, text string, scale int, col Color) {
	for i, ch in text {
		mut c := ch
		if c >= `a` && c <= `z` {
			c = c - 32
		}
		draw_char(renderer, x + i * 8 * scale, y, c, scale, col)
	}
}

pub fn draw_text_centered(renderer &Renderer, cx int, y int, text string, scale int, col Color) {
	w := text.len * 8 * scale
	draw_text(renderer, cx - w / 2, y, text, scale, col)
}
