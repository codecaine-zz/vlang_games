fn draw_char(renderer &Renderer, x int, y int, ch u8, scale int, c Color) {
	if ch < 32 || ch > 126 {
		return
	}
	glyph := font_8x8[ch - 32]
	set_render_draw_color(renderer, c.r, c.g, c.b, c.a)
	for row := 0; row < 8; row++ {
		row_bits := glyph[row]
		for col := 0; col < 8; col++ {
			if (row_bits & (u8(1) << (7 - col))) != 0 {
				if scale == 1 {
					render_draw_point(renderer, x + col, y + row)
				} else {
					rect := Rect{
						x: x + col * scale
						y: y + row * scale
						w: scale
						h: scale
					}
					render_fill_rect(renderer, &rect)
				}
			}
		}
	}
}

fn draw_text(renderer &Renderer, x int, y int, text string, scale int, c Color) {
	mut cur_x := x
	for i := 0; i < text.len; i++ {
		ch := text[i]
		if ch == `\n` {
			cur_x = x
			continue
		}
		draw_char(renderer, cur_x, y, ch, scale, c)
		cur_x += 8 * scale
	}
}

fn draw_text_centered(renderer &Renderer, center_x int, y int, text string, scale int, c Color) {
	total_w := text.len * 8 * scale
	start_x := center_x - total_w / 2
	draw_text(renderer, start_x, y, text, scale, c)
}
