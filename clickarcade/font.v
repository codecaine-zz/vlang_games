pub fn draw_char(renderer &Renderer, x int, y int, c u8, scale int, color Color) {
	if c < 32 || c > 126 {
		return
	}
	font_idx := int(c - 32) * 8
	set_render_draw_color(renderer, color.r, color.g, color.b, color.a)

	for row in 0 .. 8 {
		bits := font_8x8[font_idx + row]
		for col in 0 .. 8 {
			if (bits & (0x80 >> col)) != 0 {
				if scale == 1 {
					render_draw_point(renderer, x + col, y + row)
				} else {
					rect := Rect{
						x: x + col * scale
						y: y + row * scale
						w: scale
						h: scale
					}
					render_fill_rect(renderer, &rect)
				}
			}
		}
	}
}

pub fn draw_text(renderer &Renderer, x int, y int, text string, scale int, color Color) {
	mut cur_x := x
	mut cur_y := y

	for i in 0 .. text.len {
		ch := text[i]
		if ch == `\n` {
			cur_x = x
			cur_y += 10 * scale
			continue
		}
		draw_char(renderer, cur_x, cur_y, ch, scale, color)
		cur_x += 8 * scale
	}
}

pub fn draw_text_centered(renderer &Renderer, center_x int, y int, text string, scale int, color Color) {
	text_w := text.len * 8 * scale
	start_x := center_x - text_w / 2
	draw_text(renderer, start_x, y, text, scale, color)
}

pub fn draw_text_right(renderer &Renderer, right_x int, y int, text string, scale int, color Color) {
	text_w := text.len * 8 * scale
	start_x := right_x - text_w
	draw_text(renderer, start_x, y, text, scale, color)
}
