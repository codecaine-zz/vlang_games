def render_matrix(
    draw: ImageDraw.ImageDraw,
    matrix: list[list[int]],
    palette: dict[int, tuple[int, int, int, int]],
    top_left: tuple[int, int],
    scale: int = 2,
) -> None:
    ox, oy = top_left
    for r, row in enumerate(matrix):
        for c, val in enumerate(row):
            if val == 0 or val not in palette:
                continue
            color = palette[val]
            px = ox + c * scale
            py = oy + r * scale
            draw.rectangle((px, py, px + scale - 1, py + scale - 1), fill=color)


def draw_flag_badge(
    draw: ImageDraw.ImageDraw, top_left: tuple[int, int], color: tuple[int, int, int], number_str: str
) -> None:
    ox, oy = top_left
    # Outer flag border & body
    draw.rectangle((ox + 4, oy + 4, ox + 28, oy + 28), fill=(*color, 255), outline=(10, 15, 25, 240), width=2)
    draw.polygon([(ox + 8, oy + 8), (ox + 24, oy + 16), (ox + 8, oy + 24)], fill=(255, 255, 255, 255))


