struct Color {
	r u8
	g u8
	b u8
	a u8 = 255
}

fn draw_char(renderer &Renderer, x int, y int, ch rune, scale int, color Color) {
	ascii_val := int(ch)
	if ascii_val < 32 || ascii_val > 126 {
		return
	}
	font_idx := (ascii_val - 32) * 8

	set_render_draw_color(renderer, color.r, color.g, color.b, color.a)

	for col_idx in 0 .. 8 {
		line_bits := font_8x8[font_idx + col_idx]
		for row_idx in 0 .. 8 {
			if (line_bits & (1 << u32(row_idx))) != 0 {
				rect := Rect{
					x: x + col_idx * scale
					y: y + row_idx * scale
					w: scale
					h: scale
				}
				render_fill_rect(renderer, &rect)
			}
		}
	}
}

fn draw_text(renderer &Renderer, x int, y int, text string, scale int, color Color) {
	mut current_x := x
	for ch in text {
		draw_char(renderer, current_x, y, ch, scale, color)
		current_x += 8 * scale
	}
}

fn draw_text_centered(renderer &Renderer, cx int, y int, text string, scale int, color Color) {
	text_len := text.len
	total_width := text_len * 8 * scale
	start_x := cx - (total_width / 2)
	draw_text(renderer, start_x, y, text, scale, color)
}

pub fn draw_text_centered_fitted(renderer &Renderer, cx int, y int, text string, max_scale int, max_width int, color Color) {
	mut scale := max_scale
	for scale > 1 && text.len * 8 * scale > max_width {
		scale--
	}
	draw_text_centered(renderer, cx, y, text, scale, color)
}

struct Button {
pub mut:
	x            int
	y            int
	w            int
	h            int
	text         string
	bg_color     Color
	hover_color  Color
	text_color   Color
	border_color Color
}

fn (b Button) is_hovered(mx int, my int) bool {
	return mx >= b.x && mx <= b.x + b.w && my >= b.y && my <= b.y + b.h
}

fn (b Button) render(renderer &Renderer, mx int, my int) {
	hovered := b.is_hovered(mx, my)
	bg := if hovered { b.hover_color } else { b.bg_color }
	
	rect := Rect{
		x: b.x
		y: b.y
		w: b.w
		h: b.h
	}
	set_render_draw_color(renderer, bg.r, bg.g, bg.b, bg.a)
	render_fill_rect(renderer, &rect)

	set_render_draw_color(renderer, b.border_color.r, b.border_color.g, b.border_color.b, b.border_color.a)
	render_draw_rect(renderer, &rect)

	cx := b.x + b.w / 2
	mut scale := 2
	if b.text.len * 16 > b.w - 8 {
		scale = 1
	}
	cy := b.y + (b.h - 8 * scale) / 2
	draw_text_centered(renderer, cx, cy, b.text, scale, b.text_color)
}
