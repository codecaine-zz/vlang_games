pub fn draw_char(renderer &Renderer, ch u8, px int, py int, scale int, col Color) {
	if ch < 32 || ch > 96 { return }
	offset := int(ch - 32) * 8
	set_render_draw_color(renderer, col.r, col.g, col.b, 255)
	for row in 0 .. 8 {
		byte_val := font_data[offset + row]
		for col_idx in 0 .. 8 {
			if (byte_val & (0x80 >> col_idx)) != 0 {
				if scale == 1 {
					render_draw_point(renderer, px + col_idx, py + row)
				} else {
					rect := Rect{
						x: px + col_idx * scale
						y: py + row * scale
						w: scale
						h: scale
					}
					render_fill_rect(renderer, &rect)
				}
			}
		}
	}
}

pub fn draw_text(renderer &Renderer, text string, px int, py int, scale int, col Color) {
	mut cur_x := px
	upper := text.to_upper()
	for i in 0 .. upper.len {
		draw_char(renderer, upper[i], cur_x, py, scale, col)
		cur_x += 8 * scale
	}
}

pub fn draw_text_shadow(renderer &Renderer, text string, px int, py int, scale int, col Color, shadow_col Color) {
	draw_text(renderer, text, px + scale, py + scale, scale, shadow_col)
	draw_text(renderer, text, px, py, scale, col)
}

pub fn draw_text_centered_shadow(renderer &Renderer, text string, cx int, py int, scale int, col Color, shadow_col Color) {
	w := text.len * 8 * scale
	px := cx - w / 2
	draw_text_shadow(renderer, text, px, py, scale, col, shadow_col)
}
